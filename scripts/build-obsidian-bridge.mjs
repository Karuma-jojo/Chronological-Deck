import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const pluginDir = path.join(root, "obsidian-plugin");
const outPath = process.argv[2] ? path.resolve(process.argv[2]) : path.join(pluginDir, "main.bundle.js");

const modules = [
  ["./archive-contract-v3", path.join(pluginDir, "archive-contract-v3.js")],
  ["./main-v043", path.join(pluginDir, "main-v043.js")],
  ["./main-v3", path.join(pluginDir, "main.js")],
];

function wrapModule(id, source) {
  return `__chronoFactories[${JSON.stringify(id)}] = function(module, exports, require) {\n${source}\n};\n`;
}

let output = `"use strict";\n\n// Generated by scripts/build-obsidian-bridge.mjs.\n// Do not edit the release bundle directly.\nconst __nativeRequire = require;\nconst __chronoFactories = Object.create(null);\nconst __chronoCache = Object.create(null);\n\n`;
for (const [id, file] of modules) output += wrapModule(id, fs.readFileSync(file, "utf8"));
output += `\nfunction __chronoRequire(id) {\n  if (!Object.prototype.hasOwnProperty.call(__chronoFactories, id)) return __nativeRequire(id);\n  if (__chronoCache[id]) return __chronoCache[id].exports;\n  const module = { exports: {} };\n  __chronoCache[id] = module;\n  __chronoFactories[id](module, module.exports, __chronoRequire);\n  return module.exports;\n}\n\nmodule.exports = __chronoRequire("./main-v3");\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output, "utf8");
console.log(`Built ${outPath}`);
